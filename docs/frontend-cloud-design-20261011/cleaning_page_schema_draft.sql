-- 不写入演示设备、默认速度或安全阈值。基础表和当前 JDBC 调用保持原样。

CREATE TABLE IF NOT EXISTS cleaning_system_profile (
    system_id VARCHAR(64) NOT NULL COMMENT '复用 cleaning_system 的稳定系统ID',
    system_name VARCHAR(128) NOT NULL COMMENT '系统显示名称',
    tank_name VARCHAR(128) NULL COMMENT '罐体显示名称，未知不编造',
    total_travel_m DECIMAL(12,4) NULL COMMENT '机械总行程，不等于本轮目标行程',
    timezone_id VARCHAR(64) NOT NULL DEFAULT 'Asia/Shanghai' COMMENT '自然周期统计时区',
    enabled_at DATETIME(3) NULL COMMENT '实际启用时间',
    version BIGINT UNSIGNED NOT NULL COMMENT '档案修订版本',
    updated_at DATETIME(3) NOT NULL COMMENT '云端档案更新UTC时间',
    PRIMARY KEY (system_id),
    CONSTRAINT fk_page_profile_system FOREIGN KEY (system_id) REFERENCES cleaning_system(system_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='页面显示所需系统档案扩展';

CREATE TABLE IF NOT EXISTS cleaning_winch_profile (
    winch_id VARCHAR(64) NOT NULL COMMENT '复用 cleaning_winch 的绞机ID',
    winch_name VARCHAR(128) NOT NULL COMMENT '显示名称',
    installation_position VARCHAR(128) NULL COMMENT '档案位置',
    rated_load_kg DECIMAL(14,4) NULL COMMENT '额定载荷，仅档案展示，非安全停机阈值',
    rated_speed_m_per_min DECIMAL(12,4) NULL COMMENT '额定速度，非当前实际速度',
    lifetime_running_seconds BIGINT UNSIGNED NULL COMMENT '单一权威来源的累计运行秒数',
    running_time_source VARCHAR(64) NULL COMMENT 'PLC计时或BOX事件汇总；不得两端相加',
    last_maintenance_at DATETIME(3) NULL COMMENT '最近真实检修UTC时间',
    version BIGINT UNSIGNED NOT NULL COMMENT '档案版本',
    PRIMARY KEY (winch_id),
    CONSTRAINT fk_page_profile_winch FOREIGN KEY (winch_id) REFERENCES cleaning_winch(winch_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='绞机页面档案，不保存实时采样';

CREATE TABLE IF NOT EXISTS cleaning_rope_binding_history (
    system_id VARCHAR(64) NOT NULL COMMENT '发生时系统ID',
    binding_version BIGINT UNSIGNED NOT NULL COMMENT '系统拓扑绑定版本',
    rope_id VARCHAR(64) NOT NULL COMMENT '物理索ID',
    winch_id VARCHAR(64) NOT NULL COMMENT '发生时绞机ID',
    winch_slot_no TINYINT UNSIGNED NOT NULL COMMENT '发生时绞机槽位1至4',
    rope_slot_no TINYINT UNSIGNED NOT NULL COMMENT '发生时索槽位1或2',
    sensor_id VARCHAR(64) NOT NULL COMMENT '该版本使用的实际传感器ID',
    sensor_name VARCHAR(128) NULL COMMENT '该版本显示名称',
    position_text VARCHAR(128) NULL COMMENT '该版本安装位置',
    legacy_metric VARCHAR(32) NULL COMMENT '前端旧角色键；不替代物理索身份',
    effective_from DATETIME(3) NOT NULL COMMENT '生效UTC时间，含起点',
    effective_to DATETIME(3) NULL COMMENT '失效UTC时间，不含终点；空表示当前',
    PRIMARY KEY (system_id, binding_version, rope_id),
    UNIQUE KEY uk_binding_slot (system_id, binding_version, winch_slot_no, rope_slot_no),
    UNIQUE KEY uk_binding_sensor (system_id, binding_version, sensor_id),
    KEY idx_binding_time (system_id, effective_from, effective_to),
    CONSTRAINT fk_binding_system FOREIGN KEY (system_id) REFERENCES cleaning_system(system_id),
    CONSTRAINT ck_binding_slots CHECK (winch_slot_no BETWEEN 1 AND 4 AND rope_slot_no BETWEEN 1 AND 2),
    CONSTRAINT ck_binding_time CHECK (effective_to IS NULL OR effective_to > effective_from)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='只追加绑定历史；更换传感器不改写旧曲线归属';

CREATE TABLE IF NOT EXISTS cleaning_settings_revision (
    box_id VARCHAR(64) NOT NULL COMMENT '目标盒子ID',
