    CONSTRAINT fk_round_session_box FOREIGN KEY (session_id, box_id) REFERENCES cleaning_session(session_id, box_id),
    CONSTRAINT ck_round_no CHECK (round_no > 0),
    CONSTRAINT ck_round_time CHECK (finished_at IS NULL OR finished_at >= started_at)
