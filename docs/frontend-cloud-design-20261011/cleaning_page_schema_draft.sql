CREATE TABLE IF NOT EXISTS cleaning_round_metric (
    session_id VARCHAR(128) NOT NULL COMMENT '会话ID',
    round_no INT NOT NULL COMMENT '轮次号',
    dimension_type VARCHAR(32) NOT NULL COMMENT 'GROUP/ROPE/WINCH',
    dimension_id VARCHAR(64) NOT NULL COMMENT '系统/索/绞机稳定ID',
