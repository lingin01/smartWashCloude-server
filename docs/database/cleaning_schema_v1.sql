    CONSTRAINT ck_alarm_time CHECK (recovered_at IS NULL OR recovered_at >= occurred_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_bin COMMENT='告警事实和人工处置版本独立';

