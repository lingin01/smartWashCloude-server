-- 清洗云端基础表V1，2026-10-12：14张清洗表，复用已有t_user。
-- 全新目标库建表设计；不创建/切换数据库，不删除数据，不包含种子数据或校验码。
-- 目标MySQL 8.0.16及以上，执行前核对版本和CHECK支持。
-- 已有库不能直接用本文件替代迁移：IF NOT EXISTS不会补列、索引和约束。
-- 时间统一UTC存取，自然周期按Asia/Shanghai计算。

CREATE TABLE IF NOT EXISTS cleaning_system (
    system_id VARCHAR(64) NOT NULL,
    tank_id VARCHAR(64) NULL,
    box_id VARCHAR(64) NOT NULL,
    ring_id VARCHAR(64) NOT NULL,
    ring_own_weight_kg DECIMAL(12,3) NULL COMMENT '圆环自重，不是实时拉力或安全阈值',
    system_name VARCHAR(128) NULL,
    tank_name VARCHAR(128) NULL,
    binding_version BIGINT UNSIGNED NOT NULL DEFAULT 1 COMMENT '云端生成并人工导入的身份配置版本',
    enabled BOOLEAN NOT NULL DEFAULT TRUE COMMENT '档案启用不代表现场运行',
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (system_id),
    UNIQUE KEY uk_system_box (box_id),
    UNIQUE KEY uk_system_box_pair (system_id, box_id),
    CONSTRAINT ck_system_binding_version CHECK (binding_version > 0)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_bin COMMENT='统一系统、罐体、盒子和圆环身份';

CREATE TABLE IF NOT EXISTS cleaning_winch (
    winch_id VARCHAR(64) NOT NULL,
    system_id VARCHAR(64) NOT NULL,
    slot_no TINYINT UNSIGNED NOT NULL COMMENT '本系统位置1至4，与盒子本地绑定一致',
    winch_name VARCHAR(128) NULL,
    installation_position VARCHAR(128) NULL,
    lifetime_running_seconds BIGINT UNSIGNED NULL COMMENT '权威来源累计秒数，未知为空',
    running_time_source VARCHAR(32) NULL,
    last_maintenance_at DATETIME(3) NULL,
    PRIMARY KEY (winch_id),
    UNIQUE KEY uk_system_slot (system_id, slot_no),
    CONSTRAINT fk_winch_system FOREIGN KEY (system_id) REFERENCES cleaning_system(system_id),
    CONSTRAINT ck_winch_slot CHECK (slot_no BETWEEN 1 AND 4)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_bin COMMENT='四台绞机，不按单机分别建表';

CREATE TABLE IF NOT EXISTS cleaning_rope_sensor (
    rope_id VARCHAR(64) NOT NULL,
    winch_id VARCHAR(64) NOT NULL,
    slot_no TINYINT UNSIGNED NOT NULL COMMENT '本机索和传感器位置1或2',
    tension_sensor_id VARCHAR(64) NOT NULL,
    sensor_name VARCHAR(128) NULL,
    warning_tension_kg DECIMAL(14,4) NULL COMMENT '盒子已应用单索预警值，不是本机平均阈值',
    stop_tension_kg DECIMAL(14,4) NULL,
    breaking_boundary_kg DECIMAL(14,4) NULL COMMENT '物理失效边界，不能当作停机阈值',
    safety_policy_version VARCHAR(64) NULL,
    safety_applied_at DATETIME(3) NULL,
    PRIMARY KEY (rope_id),
    UNIQUE KEY uk_rope_sensor (tension_sensor_id),
    UNIQUE KEY uk_winch_rope_slot (winch_id, slot_no),
    CONSTRAINT fk_rope_winch FOREIGN KEY (winch_id) REFERENCES cleaning_winch(winch_id),
    CONSTRAINT ck_rope_slot CHECK (slot_no BETWEEN 1 AND 2),
    CONSTRAINT ck_rope_warning CHECK (warning_tension_kg IS NULL OR warning_tension_kg >= 0),
    CONSTRAINT ck_rope_stop CHECK (stop_tension_kg IS NULL OR stop_tension_kg > 0),
    CONSTRAINT ck_rope_boundary CHECK (breaking_boundary_kg IS NULL OR breaking_boundary_kg > 0),
    CONSTRAINT ck_rope_threshold_order CHECK (warning_tension_kg IS NULL OR stop_tension_kg IS NULL OR warning_tension_kg < stop_tension_kg),
    CONSTRAINT ck_rope_breaking CHECK (stop_tension_kg IS NULL OR breaking_boundary_kg IS NULL OR stop_tension_kg < breaking_boundary_kg)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_bin COMMENT='八索八传感器；不写入演示安全值';

CREATE TABLE IF NOT EXISTS cleaning_box_access (
    box_id VARCHAR(64) NOT NULL,
    access_code_ciphertext VARBINARY(1024) NULL COMMENT '固定校验码可读取密文；加密密钥不存本表',
    encryption_key_ref VARCHAR(128) NULL COMMENT '云端受控配置的密钥标识，不是密钥本身',
    credential_version BIGINT UNSIGNED NOT NULL DEFAULT 1,
    enabled BOOLEAN NOT NULL DEFAULT FALSE,
    exported_binding_version BIGINT UNSIGNED NULL,
    exported_at DATETIME(3) NULL COMMENT '导出不代表盒子已经安装',
    reported_binding_version BIGINT UNSIGNED NULL COMMENT '盒子明确报告的版本，未报告为空',
    reported_at DATETIME(3) NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (box_id),
    CONSTRAINT fk_access_box FOREIGN KEY (box_id) REFERENCES cleaning_system(box_id),
    CONSTRAINT ck_access_version CHECK (credential_version > 0),
    CONSTRAINT ck_access_material CHECK (enabled = FALSE OR (access_code_ciphertext IS NOT NULL AND encryption_key_ref IS NOT NULL))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_bin COMMENT='一盒一校验码，不进入普通VO或日志';

CREATE TABLE IF NOT EXISTS cleaning_settings_revision (
    box_id VARCHAR(64) NOT NULL,
    config_version BIGINT UNSIGNED NOT NULL COMMENT '盒子实际生效版本',
    start_time TIME NOT NULL COMMENT '现场时区HH:mm，业务层拒绝秒和超范围时间',
    interval_seconds BIGINT UNSIGNED NOT NULL,
    group_speed_m_per_min DECIMAL(12,4) NOT NULL,
    speed_level INT NULL COMMENT '确认挡位映射后才保存',
    request_id VARCHAR(128) NULL,
    binding_version BIGINT UNSIGNED NULL,
    applied_at DATETIME(3) NOT NULL,
    received_at DATETIME(3) NOT NULL,
    PRIMARY KEY (box_id, config_version),
    KEY idx_settings_applied (box_id, applied_at),
    CONSTRAINT fk_settings_box FOREIGN KEY (box_id) REFERENCES cleaning_system(box_id),
    CONSTRAINT ck_settings_interval CHECK (interval_seconds > 0),
    CONSTRAINT ck_settings_speed CHECK (group_speed_m_per_min > 0 AND group_speed_m_per_min <= 10)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_bin COMMENT='仅保存已生效三参数，申请值在命令表';

CREATE TABLE IF NOT EXISTS cleaning_session (
    session_id VARCHAR(128) NOT NULL COMMENT '持续自动作业，不按午夜拆分',
    system_id VARCHAR(64) NOT NULL,
    box_id VARCHAR(64) NOT NULL,
    started_at DATETIME(3) NOT NULL,
    finished_at DATETIME(3) NULL,
    status VARCHAR(32) NOT NULL DEFAULT 'RUNNING',
    stop_reason VARCHAR(64) NULL,
    started_by VARCHAR(64) NULL,
    settings_version BIGINT UNSIGNED NULL,
    binding_version BIGINT UNSIGNED NULL,
    identity_snapshot_json JSON NULL COMMENT '当时统一ID关系，不含校验码或PLC连接凭据',
    completed_rounds BIGINT UNSIGNED NULL,
    abnormal_rounds BIGINT UNSIGNED NULL,
    raw_sample_count BIGINT UNSIGNED NULL,
    box_alarm_count BIGINT UNSIGNED NULL COMMENT '计数未知为空，不能默认编造0',
    revision BIGINT UNSIGNED NOT NULL,
    data_complete BOOLEAN NOT NULL DEFAULT FALSE,
    PRIMARY KEY (session_id),
    UNIQUE KEY uk_session_box (session_id, box_id),
    KEY idx_session_system_start (system_id, started_at),
    CONSTRAINT fk_session_system_box FOREIGN KEY (system_id, box_id) REFERENCES cleaning_system(system_id, box_id),
    CONSTRAINT ck_session_time CHECK (finished_at IS NULL OR finished_at >= started_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_bin COMMENT='PLC自动作业事实，检修不计入';

CREATE TABLE IF NOT EXISTS cleaning_round (
    session_id VARCHAR(128) NOT NULL,
    round_no INT NOT NULL COMMENT '一次正常上下；自恢复往返不递增',
    box_id VARCHAR(64) NOT NULL,
    round_id VARCHAR(192) NOT NULL COMMENT '详情稳定ID，不是今日第N次显示编号',
    started_at DATETIME(3) NOT NULL,
    finished_at DATETIME(3) NULL,
    result VARCHAR(32) NOT NULL DEFAULT 'RUNNING' COMMENT 'RUNNING/COMPLETED/FAILED/INTERRUPTED/UNKNOWN',
    stop_reason VARCHAR(64) NULL,
    descent_m DECIMAL(12,4) NULL,
    ascent_m DECIMAL(12,4) NULL,
    settings_version BIGINT UNSIGNED NULL,
    binding_version BIGINT UNSIGNED NULL,
    recovery_count INT UNSIGNED NULL,
    alarm_count BIGINT UNSIGNED NULL,
    maximum_single_rope_tension_kg DECIMAL(14,4) NULL COMMENT '只有完整统计依据时填，不从稀疏点推断全程最大值',
    maximum_rope_id VARCHAR(64) NULL,
    statistics_eligible BOOLEAN NOT NULL DEFAULT FALSE,
    data_complete BOOLEAN NOT NULL DEFAULT FALSE,
    revision BIGINT UNSIGNED NOT NULL,
    PRIMARY KEY (session_id, round_no),
    UNIQUE KEY uk_round_id (round_id),
    KEY idx_round_box_start (box_id, started_at),
    KEY idx_round_box_finish (box_id, finished_at),
    CONSTRAINT fk_round_session_box FOREIGN KEY (session_id, box_id) REFERENCES cleaning_session(session_id, box_id),
    CONSTRAINT ck_round_no CHECK (round_no > 0),
    CONSTRAINT ck_round_time CHECK (finished_at IS NULL OR finished_at >= started_at),
    CONSTRAINT ck_round_eligible CHECK (statistics_eligible = FALSE OR (result = 'COMPLETED' AND finished_at IS NOT NULL AND data_complete = TRUE))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_bin COMMENT='轮次终态决定资格，不能根据一个有效点宣布完成';

CREATE TABLE IF NOT EXISTS cleaning_telemetry_batch (
    box_id VARCHAR(64) NOT NULL,
    batch_id VARCHAR(128) NOT NULL,
    first_sequence BIGINT UNSIGNED NOT NULL,
    last_sequence BIGINT UNSIGNED NOT NULL,
    stream_id VARCHAR(128) NULL COMMENT '旧协议可空，新协议必须提供稳定身份',
    payload_hash CHAR(64) NULL COMMENT '同批次不同内容须拒绝，不能INSERT IGNORE静默丢弃',
    record_count INT UNSIGNED NULL,
    ack_state VARCHAR(24) NOT NULL DEFAULT 'PENDING',
    ack_sent_at DATETIME(3) NULL,
    received_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (box_id, batch_id),
    KEY idx_batch_ack (ack_state, received_at),
    CONSTRAINT ck_batch_range CHECK (last_sequence >= first_sequence)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_bin COMMENT='批次事务登记；提交后才能发保存ACK';

CREATE TABLE IF NOT EXISTS cleaning_telemetry_segment (
    box_id VARCHAR(64) NOT NULL,
    batch_id VARCHAR(128) NOT NULL,
    telemetry_sequence BIGINT UNSIGNED NOT NULL,
    session_id VARCHAR(128) NOT NULL,
    round_no INT NOT NULL DEFAULT 0 COMMENT '旧DAO兼容，0为未关联；新自动轮次必须大于0',
    direction VARCHAR(16) NULL,
    started_at DATETIME(3) NULL,
    finished_at DATETIME(3) NULL,
    start_height_m DECIMAL(10,3) NULL,
    end_height_m DECIMAL(10,3) NULL,
    trigger_reason VARCHAR(64) NULL,
    policy_version VARCHAR(64) NULL,
    stream_id VARCHAR(128) NULL,
    source_sample_sequence BIGINT UNSIGNED NULL,
    segment_id VARCHAR(128) NULL,
    record_kind VARCHAR(16) NOT NULL DEFAULT 'LEGACY' COMMENT 'POINT/AGGREGATE/LEGACY，旧行不冒充真实点',
    record_scope VARCHAR(24) NOT NULL DEFAULT 'UNKNOWN' COMMENT 'NORMAL_UP/EXCEPTION/RECOVERY/UNKNOWN',
    mode VARCHAR(24) NULL,
    start_height_valid BOOLEAN NULL,
    end_height_valid BOOLEAN NULL,
    settings_version BIGINT UNSIGNED NULL,
    binding_version BIGINT UNSIGNED NULL,
    recovery_event_id VARCHAR(128) NULL,
    event_code VARCHAR(64) NULL,
    PRIMARY KEY (box_id, batch_id, telemetry_sequence),
    UNIQUE KEY uk_segment_source (box_id, stream_id, telemetry_sequence),
    KEY idx_box_time (box_id, started_at),
    KEY idx_session_round (session_id, round_no),
    KEY idx_segment_curve (box_id, session_id, round_no, direction, record_scope, started_at),
    CONSTRAINT fk_segment_batch FOREIGN KEY (box_id, batch_id) REFERENCES cleaning_telemetry_batch(box_id, batch_id),
    CONSTRAINT ck_segment_time CHECK (finished_at IS NULL OR started_at IS NULL OR finished_at >= started_at),
    CONSTRAINT ck_segment_normal_up CHECK (record_scope <> 'NORMAL_UP' OR (direction IS NOT NULL AND direction = 'UP'))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_bin COMMENT='0.5m留点与明确摘要，保留旧分段列兼容';

CREATE TABLE IF NOT EXISTS cleaning_segment_measurement (
    box_id VARCHAR(64) NOT NULL,
    batch_id VARCHAR(128) NOT NULL,
    telemetry_sequence BIGINT UNSIGNED NOT NULL,
    metric_type VARCHAR(32) NOT NULL,
    channel_no TINYINT UNSIGNED NOT NULL,
    target_id VARCHAR(64) NULL,
    minimum_value DECIMAL(14,4) NULL,
    maximum_value DECIMAL(14,4) NULL,
    average_value DECIMAL(14,4) NULL,
    latest_value DECIMAL(14,4) NULL,
    sample_count BIGINT UNSIGNED NOT NULL DEFAULT 0,
    sum_value DECIMAL(30,8) NULL COMMENT '仅保存真实累计，不能从四舍五入均值反推',
    unit_code VARCHAR(16) NULL COMMENT 'KG/KGF/M_PER_MIN/NM，单位未知不猜',
    valid BOOLEAN NULL,
    sensor_id VARCHAR(64) NULL,
    winch_id VARCHAR(64) NULL,
    rope_id VARCHAR(64) NULL,
    aggregate_method VARCHAR(48) NULL,
    PRIMARY KEY (box_id, batch_id, telemetry_sequence, metric_type, channel_no),
    KEY idx_target_metric (target_id, metric_type),
    CONSTRAINT fk_measurement_segment FOREIGN KEY (box_id, batch_id, telemetry_sequence) REFERENCES cleaning_telemetry_segment(box_id, batch_id, telemetry_sequence),
    CONSTRAINT ck_measurement_channel CHECK (channel_no BETWEEN 1 AND 8),
    CONSTRAINT ck_measurement_range CHECK (minimum_value IS NULL OR maximum_value IS NULL OR maximum_value >= minimum_value)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_bin COMMENT='每个历史记录的各路测量；不按传感器分表';

CREATE TABLE IF NOT EXISTS cleaning_recovery_event (
    box_id VARCHAR(64) NOT NULL,
    event_id VARCHAR(128) NOT NULL COMMENT '一次PLC恢复过程，多次尝试属于同过程',
    session_id VARCHAR(128) NULL,
    round_no INT NULL,
    started_at DATETIME(3) NOT NULL,
    finished_at DATETIME(3) NULL,
    result VARCHAR(24) NOT NULL COMMENT 'RECOVERING/RECOVERED/FAILED/UNKNOWN',
    attempt_count TINYINT UNSIGNED NULL COMMENT 'PLC反馈次数，未知为空',
    final_fault_confirmed BOOLEAN NULL,
    source_fault_code VARCHAR(64) NULL,
    cause_code VARCHAR(64) NULL,
    started_direction VARCHAR(16) NULL,
    ended_direction VARCHAR(16) NULL,
    revision BIGINT UNSIGNED NOT NULL,
    PRIMARY KEY (box_id, event_id),
    KEY idx_recovery_round (box_id, session_id, round_no, started_at),
    CONSTRAINT ck_recovery_attempt CHECK (attempt_count IS NULL OR attempt_count <= 5),
    CONSTRAINT ck_recovery_time CHECK (finished_at IS NULL OR finished_at >= started_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_bin COMMENT='恢复不等于最终故障告警，不递增正常轮次';

CREATE TABLE IF NOT EXISTS cleaning_alarm_event (
    producer_id VARCHAR(64) NOT NULL,
    event_id VARCHAR(128) NOT NULL COMMENT '源端alarmId，不以alarmCode当事件ID',
    source VARCHAR(32) NOT NULL,
    system_id VARCHAR(64) NULL,
    box_id VARCHAR(64) NULL,
    session_id VARCHAR(128) NULL,
    round_no INT NULL,
    winch_id VARCHAR(64) NULL,
    rope_id VARCHAR(64) NULL,
    sensor_id VARCHAR(64) NULL,
    alarm_code VARCHAR(64) NOT NULL,
    source_fault_code VARCHAR(64) NULL,
    severity VARCHAR(24) NOT NULL,
    trigger_value DECIMAL(18,6) NULL,
    threshold_value DECIMAL(18,6) NULL,
    threshold_kind VARCHAR(24) NULL COMMENT 'WARNING/PROTECTION，仅有源端事实时填写',
    safety_policy_version VARCHAR(64) NULL,
    binding_version BIGINT UNSIGNED NULL,
    actual_action VARCHAR(64) NULL COMMENT '盒子明确执行的动作，不由云端等级推断',
    unit_code VARCHAR(16) NULL,
    notice_json JSON NOT NULL COMMENT '公共中文提示，不含堆栈/密码/原始控制报文',
    active BOOLEAN NOT NULL,
    occurred_at DATETIME(3) NOT NULL,
    recovered_at DATETIME(3) NULL COMMENT '设备恢复事实，人工处理不能修改',
    received_at DATETIME(3) NOT NULL,
    handling_state VARCHAR(24) NOT NULL DEFAULT 'UNHANDLED',
    source_revision BIGINT UNSIGNED NULL,
    handling_revision BIGINT UNSIGNED NOT NULL DEFAULT 0,
    PRIMARY KEY (producer_id, event_id),
    KEY idx_alarm_system_time (system_id, occurred_at),
